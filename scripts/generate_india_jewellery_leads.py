def _uniq_handles(leads: list[dict[str, str]]) -> list[dict[str, str]]:
    seen: set[str] = set()
    out: list[dict[str, str]] = []
    for row in leads:
        h = row["instagram"].strip().lstrip("@").lower()
        if h in seen:
            continue
        seen.add(h)
        out.append(row)
    return out


def render_lead(idx: int, row: dict[str, str]) -> str:
    handle = row["instagram"].strip().lstrip("@")
    url = f"https://www.instagram.com/{handle}/"
    lines = [
        "",
        "=" * 50,
        f"LEAD #{idx}",
        "=" * 50,
        f"Business Name: {row['business_name']}",
        f"Instagram Handle: @{handle}",
        f"Instagram URL: {url}",
        f"Followers Count: {row['followers']}",
        f"City: {row['city']}",
        f"State: {row['state']}",
        f"Business Type: {row['business_type']}",
        f"WhatsApp Number: {row['whatsapp']}",
        f"Email: {row['email']}",
        f"Ordering Method: {row['ordering_method']}",
        f"Website Present: {row['website_present']}",
        f"Website URL: {row['website_url']}",
        f"Recent Activity Date: {row['recent_activity']}",
        f"Average Engagement: {row['avg_engagement']}",
        f"Bio Text: {row['bio_text']}",
        f"Keywords: {row['keywords']}",
        f"Reason Qualified: {row['reason_qualified']}",
        f"Potential Services Needed: {row['potential_services']}",
        f"Google Maps Link: {row['google_maps']}",
        f"Lead Quality Score: {row['lead_score']}/10",
        f"Notes: {row['notes']}",
    ]
    return "\n".join(lines) + "\n"


def main() -> None:
    leads = _uniq_handles(LEADS)
    # If under 100, fail loudly (we should never ship placeholders).
    if len(leads) < 100:
        raise SystemExit(f"Expected >=100 unique leads after dedupe; got {len(leads)}")

    # Hard cap to 100 for this deliverable file version.
    leads = leads[:100]

    out_path = Path("/workspace/india_jewellery_instagram_leads.txt")
    header = "\n".join(
        [
            "INDIA JEWELLERY INSTAGRAM LEADS (SMB / WhatsApp-DM first)",
            "Generated via public web index snippets (May 2026).",
            "Disclaimer: follower counts, engagement, and recency must be verified in-app.",
            "",
        ]
    )
    chunks: list[str] = [header]
    for i, row in enumerate(leads, start=1):
        chunks.append(render_lead(i, row))
    out_path.write_text("".join(chunks), encoding="utf-8")

    meta = {
        "count": len(leads),
        "unique_handles": [r["instagram"].strip().lstrip("@") for r in leads],
    }
    Path("/workspace/india_jewellery_instagram_leads.meta.json").write_text(
        json.dumps(meta, indent=2, ensure_ascii=False) + "\n", encoding="utf-8"
    )


if __name__ == "__main__":
    main()
