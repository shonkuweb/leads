NA = "Not verifiable from public search; confirm on Instagram"


def render_lead(i: int, row: dict[str, str]) -> str:
    handle = row["handle"].strip().lstrip("@")
    ig_url = f"https://www.instagram.com/{handle}/"
    lines = [
        "=" * 50,
        f"LEAD #{i}",
        "=" * 50,
        f"Business Name: {row.get('business_name', '')}",
        f"Instagram Handle: @{handle}",
        f"Instagram URL: {ig_url}",
        f"Followers Count: {row.get('followers_count') or NA}",
        f"City: {row.get('city', '')}",
        f"State: {row.get('state', '')}",
        f"Business Type: {row.get('business_type', '')}",
        f"WhatsApp Number: {row.get('whatsapp', '') or 'Not listed in public index; check Instagram bio/posts'}",
        f"Email: {row.get('email', '') or 'Not listed in public index; check Instagram bio'}",
        f"Ordering Method: {row.get('ordering_method', '')}",
        f"Website Present: {row.get('website_present', '')}",
        f"Website URL: {row.get('website_url', '')}",
        f"Recent Activity Date: {row.get('recent_activity') or NA}",
        f"Average Engagement: {row.get('avg_engagement') or NA}",
        f"Bio Text: {row.get('bio_text', '')}",
        f"Keywords: {row.get('keywords', '')}",
        f"Reason Qualified: {row.get('reason_qualified', '')}",
        f"Potential Services Needed: {row.get('services', '')}",
        f"Google Maps Link: {row.get('maps', '') or 'Not captured'}",
        f"Lead Quality Score: {row.get('score', '')}",
        f"Notes: {row.get('notes', '')}",
        "",
    ]
    return "\n".join(lines)


